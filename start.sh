#!/bin/bash
# Starts the backend API and frontend static server using the ports in config.yaml.
set -euo pipefail

cd "$(dirname "$0")"

read_port() {
  python3 -c "
import yaml
with open('config.yaml') as f:
    print(yaml.safe_load(f)['$1']['port'])
"
}

BACKEND_PORT=$(read_port backend)
FRONTEND_PORT=$(read_port frontend)
BACKEND_HOST=127.0.0.1

kill_port() {
  local pids
  pids=$(lsof -ti "tcp:$1" -sTCP:LISTEN 2>/dev/null || true)
  if [ -n "$pids" ]; then
    echo "Killing existing process(es) on port $1: $pids"
    kill -9 $pids 2>/dev/null || true
  fi
}

kill_port "$BACKEND_PORT"
kill_port "$FRONTEND_PORT"

cat > frontend/.env.local <<EOF
# Generated by start.sh from config.yaml — do not edit by hand.
VITE_API_BASE_URL=http://${BACKEND_HOST}:${BACKEND_PORT}/api
EOF

python -m contacts serve --host "$BACKEND_HOST" --port "$BACKEND_PORT" &
BACKEND_PID=$!

(cd frontend && npm run dev -- --port "$FRONTEND_PORT" --strictPort) &
FRONTEND_PID=$!

trap 'kill "$BACKEND_PID" "$FRONTEND_PID" 2>/dev/null' EXIT INT TERM

echo "Backend:  http://${BACKEND_HOST}:${BACKEND_PORT}"
echo "Frontend: http://localhost:${FRONTEND_PORT}"

wait
