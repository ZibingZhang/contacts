#!/bin/bash
# Starts the backend API and frontend static server using the ports in config.yaml.
#
# Usage: ./start.sh [--env dev|prod] [--log-http]
#   prod (default): production frontend build served via `vite preview`,
#                    backend without debug mode.
#   dev:             frontend `vite` dev server (HMR, React StrictMode),
#                    backend with --debug.
#   --log-http:      log iCloud HTTP request/response bodies to a file
#                     under logs/ (off by default -- too noisy for regular
#                     development).
set -euo pipefail

cd "$(dirname "$0")"

ENV=prod
LOG_HTTP=0
while [ $# -gt 0 ]; do
  case "$1" in
    --env)
      ENV="${2:-}"
      shift 2
      ;;
    --env=*)
      ENV="${1#--env=}"
      shift
      ;;
    --log-http)
      LOG_HTTP=1
      shift
      ;;
    *)
      echo "Unknown argument: $1" >&2
      exit 1
      ;;
  esac
done

case "$ENV" in
  dev|prod) ;;
  *)
    echo "Invalid --env value: $ENV (expected 'dev' or 'prod')" >&2
    exit 1
    ;;
esac

read_port() {
  python3 -c "
import yaml
with open('config.yaml') as f:
    print(yaml.safe_load(f)['$1']['port'])
"
}

BACKEND_PORT=$(read_port backend)
FRONTEND_PORT=$(read_port frontend)
BACKEND_HOST=127.0.0.1

kill_port() {
  local pids
  pids=$(lsof -ti "tcp:$1" -sTCP:LISTEN 2>/dev/null || true)
  if [ -n "$pids" ]; then
    echo "Killing existing process(es) on port $1: $pids"
    kill -9 $pids 2>/dev/null || true
  fi
}

kill_port "$BACKEND_PORT"
kill_port "$FRONTEND_PORT"

cat > frontend/.env.local <<EOF
# Generated by start.sh from config.yaml — do not edit by hand.
VITE_API_BASE_URL=http://${BACKEND_HOST}:${BACKEND_PORT}/api
EOF

BACKEND_ARGS=(--host "$BACKEND_HOST" --port "$BACKEND_PORT")
if [ "$ENV" = dev ]; then
  BACKEND_ARGS+=(--debug)
fi

if [ "$LOG_HTTP" = 1 ]; then
  export CONTACTS_LOG_HTTP=1
fi

python -m contacts serve "${BACKEND_ARGS[@]}" &
BACKEND_PID=$!

if [ "$ENV" = dev ]; then
  (cd frontend && npm run dev -- --port "$FRONTEND_PORT" --strictPort) &
else
  (cd frontend && npm run build && npm run preview -- --port "$FRONTEND_PORT" --strictPort) &
fi
FRONTEND_PID=$!

trap 'kill "$BACKEND_PID" "$FRONTEND_PID" 2>/dev/null' EXIT INT TERM

echo "Env:      ${ENV}"
echo "Log HTTP: ${LOG_HTTP}"
echo "Backend:  http://${BACKEND_HOST}:${BACKEND_PORT}"
echo "Frontend: http://localhost:${FRONTEND_PORT}"

wait
